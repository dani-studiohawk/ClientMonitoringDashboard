#!/usr/bin/env python3
"""Rebuild the public schema of the Supabase database as plain SQL.

Reads only the system catalogs, so it runs through the Supabase Management
API with a read-only query (no database password or direct connection).

    SUPABASE_ACCESS_TOKEN=sbp_... python3 supabase/tools/schema_snapshot.py > supabase/migrations/<ts>_baseline.sql

    # or against a local Postgres (used to verify a snapshot round-trips):
    python3 supabase/tools/schema_snapshot.py --psql "postgresql://localhost:5433/postgres"

Covers: enums, tables (columns, defaults, constraints), indexes, functions,
triggers (public tables and auth.users), RLS and policies, grants to the
Supabase roles, default privileges, and pg_cron jobs. Supabase-managed schemas
(auth, storage, vault, extensions...) are assumed to exist already.
"""
import argparse
import json
import os
import subprocess
import sys
import urllib.request

PROJECT_REF = "ylnrkfpchrzvuhqrnwco"
ROLES = ("anon", "authenticated", "service_role")


def make_runner(psql_url):
    if psql_url:
        def run(sql):
            out = subprocess.run(
                ["psql", psql_url, "-XAtq", "-v", "ON_ERROR_STOP=1", "-c",
                 f"select coalesce(json_agg(t), '[]') from ({sql}) t"],
                check=True, capture_output=True, text=True).stdout
            return json.loads(out)
        return run

    token = os.environ["SUPABASE_ACCESS_TOKEN"]

    def run(sql):
        req = urllib.request.Request(
            f"https://api.supabase.com/v1/projects/{PROJECT_REF}/database/query",
            data=json.dumps({"query": sql, "read_only": True}).encode(),
            headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req) as resp:
            return json.load(resp)
    return run


def snapshot(run):
    out = []
    emit = out.append

    emit("-- Baseline of the public schema, generated by supabase/tools/schema_snapshot.py")
    emit("-- from the live database's catalogs. Supabase-managed schemas are assumed.")
    emit("")
    emit("set search_path to public, extensions;")
    emit("set check_function_bodies = off;  -- functions reference each other; pg_dump does the same")
    emit("")
    emit('create extension if not exists "uuid-ossp" with schema extensions;')
    emit("")

    # Enums
    for r in run("""
        select t.typname as name, json_agg(e.enumlabel::text order by e.enumsortorder) as labels
        from pg_type t join pg_namespace n on n.oid = t.typnamespace
        join pg_enum e on e.enumtypid = t.oid
        where n.nspname = 'public' group by t.typname order by t.typname"""):
        labels = ", ".join("'" + l.replace("'", "''") + "'" for l in r["labels"])
        emit(f"create type public.{r['name']} as enum ({labels});")
    emit("")

    # Tables and columns
    tables = [r["name"] for r in run("""
        select c.relname as name from pg_class c join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'public' and c.relkind = 'r' order by 1""")]
    cols = run("""
        select c.relname as tbl, a.attname as col, format_type(a.atttypid, a.atttypmod) as type,
               a.attnotnull as notnull, pg_get_expr(d.adbin, d.adrelid) as def, a.attnum as num
        from pg_attribute a join pg_class c on c.oid = a.attrelid
        join pg_namespace n on n.oid = c.relnamespace
        left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
        where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
        order by c.relname, a.attnum""")
    for t in tables:
        lines = []
        for c in (c for c in cols if c["tbl"] == t):
            line = f'  "{c["col"]}" {c["type"]}'
            if c["def"] is not None:
                line += f" default {c['def']}"
            if c["notnull"]:
                line += " not null"
            lines.append(line)
        emit(f"create table public.{t} (\n" + ",\n".join(lines) + "\n);")
    emit("")

    # Constraints: primary/unique/check first, foreign keys last
    cons = run("""
        select c.relname as tbl, k.conname as name, k.contype as type, pg_get_constraintdef(k.oid) as def
        from pg_constraint k join pg_class c on c.oid = k.conrelid
        join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'public' and k.contype in ('p','u','c','f','x')
        order by (k.contype = 'f'), c.relname, k.conname""")
    for k in cons:
        emit(f'alter table public.{k["tbl"]} add constraint "{k["name"]}" {k["def"]};')
    emit("")

    # Indexes not created by constraints
    for r in run("""
        select i.indexdef as def from pg_indexes i
        where i.schemaname = 'public'
          and not exists (select 1 from pg_constraint k where k.conname = i.indexname
                          and k.connamespace = 'public'::regnamespace)
        order by i.tablename, i.indexname"""):
        emit(r["def"] + ";")
    emit("")

    # Functions
    for r in run("""
        select pg_get_functiondef(p.oid) as def from pg_proc p
        join pg_namespace n on n.oid = p.pronamespace
        where n.nspname = 'public' and p.prokind = 'f'
          and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
        order by p.proname, pg_get_function_identity_arguments(p.oid)"""):
        emit(r["def"].rstrip() + ";")
        emit("")

    # Triggers on public tables and auth.users
    for r in run("""
        select pg_get_triggerdef(t.oid) as def from pg_trigger t
        join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
        where not t.tgisinternal and (n.nspname = 'public' or (n.nspname = 'auth' and c.relname = 'users'))
          and exists (select 1 from pg_proc p join pg_namespace pn on pn.oid = p.pronamespace
                      where p.oid = t.tgfoid and pn.nspname = 'public')
        order by c.relname, t.tgname"""):
        emit(r["def"] + ";")
    emit("")

    # RLS and policies
    for r in run("""
        select c.relname as tbl, c.relrowsecurity as rls, c.relforcerowsecurity as force
        from pg_class c join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'public' and c.relkind = 'r' order by 1"""):
        if r["rls"]:
            emit(f"alter table public.{r['tbl']} enable row level security;")
        if r["force"]:
            emit(f"alter table public.{r['tbl']} force row level security;")
    for p in run("""
        select tablename as tbl, policyname as name, permissive, roles, cmd, qual, with_check
        from pg_policies where schemaname = 'public' order by tablename, policyname"""):
        roles = p["roles"] if isinstance(p["roles"], list) else p["roles"].strip("{}").split(",")
        sql = (f'create policy "{p["name"]}" on public.{p["tbl"]} as {p["permissive"].lower()} '
               f'for {p["cmd"].lower()} to {", ".join(roles)}')
        if p["qual"]:
            sql += f" using ({p['qual']})"
        if p["with_check"]:
            sql += f" with check ({p['with_check']})"
        emit(sql + ";")
    emit("")

    # Grants: table privileges and function execute for the Supabase roles
    role_list = ", ".join(f"'{r}'" for r in ROLES)
    for t in tables:
        emit(f"revoke all on public.{t} from {', '.join(ROLES)};")
    # Read ACLs directly: information_schema.role_table_grants only shows grants
    # visible to the querying role, which hides them from the read-only API user.
    for r in run(f"""
        select c.relname as tbl, r.rolname as grantee,
               string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs
        from pg_class c join pg_namespace n on n.oid = c.relnamespace
        cross join lateral aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) a
        join pg_roles r on r.oid = a.grantee
        where n.nspname = 'public' and c.relkind = 'r' and r.rolname in ({role_list})
        group by c.relname, r.rolname order by c.relname, r.rolname"""):
        emit(f"grant {r['privs'].lower()} on public.{r['tbl']} to {r['grantee']};")
    emit("")
    emit("do $$ declare f regprocedure; begin")
    emit("  for f in select p.oid::regprocedure from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind = 'f' loop")
    emit(f"    execute format('revoke execute on function %s from public, {', '.join(ROLES)}', f);")
    emit("  end loop; end $$;")
    for r in run(f"""
        select p.oid::regprocedure::text as fn, r.rolname as role
        from pg_proc p join pg_namespace n on n.oid = p.pronamespace
        cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
        join pg_roles r on r.oid = a.grantee
        where n.nspname = 'public' and p.prokind = 'f' and a.privilege_type = 'EXECUTE'
          and r.rolname in ({role_list})
        order by 1, 2"""):
        emit(f"grant execute on function {r['fn']} to {r['role']};")
    emit("alter default privileges for role postgres in schema public revoke execute on functions from public, anon;")
    emit("")

    # pg_cron jobs (commands read their auth token from Vault; no secrets here)
    jobs = run("select jobname, schedule, command from cron.job order by jobname") if run(
        "select 1 as ok from pg_extension where extname = 'pg_cron'") else []
    if jobs:
        emit("-- Scheduled jobs (requires pg_cron and pg_net; HTTP jobs read the")
        emit("-- 'cron_secret' Vault secret, which must be created separately).")
        emit("do $cron$ begin if exists (select 1 from pg_extension where extname = 'pg_cron') then")
        for j in jobs:
            cmd = j["command"].replace("\r\n", "\n").strip()
            if "eyJ" in cmd or "sb_secret_" in cmd:
                sys.exit(f"refusing to write cron job {j['jobname']}: its command contains a key")
            emit(f"  perform cron.schedule('{j['jobname']}', '{j['schedule']}', $cmd${cmd}$cmd$);")
        emit("end if; end $cron$;")

    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--psql", help="connection string of a Postgres to read instead of the live project")
    args = ap.parse_args()
    sys.stdout.write(snapshot(make_runner(args.psql)))


if __name__ == "__main__":
    main()
